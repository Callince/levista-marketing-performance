def _fit(ws, widths: dict):
    for idx, width in widths.items():
        ws.column_dimensions[get_column_letter(idx)].width = width


def _title(ws, title: str, period: tuple, span: int = 12) -> int:
    start, end = period
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=max(span, 4))
    cell = ws.cell(row=1, column=1, value=title)
    cell.font, cell.fill = TITLE_FONT, TITLE_FILL
    # Indent past the floated logo. Character units, not spaces — column A's width
    # differs per sheet, so a fixed run of spaces would land differently each time.
    cell.alignment = Alignment(vertical="center", indent=11)
    ws.row_dimensions[1].height = 34
    if LOGO_WHITE.exists():
        # Floated over the dark title fill, so it needs the white variant.
        logo = XLImage(str(LOGO_WHITE))
        logo.height = 22
        logo.width = int(22 * 3713 / 1073)
        ws.add_image(logo, "A1")
    label = (f"Reporting period: {start:%d %b %Y} – {end:%d %b %Y}"
             if start and end else "Reporting period: not stated in source files")
    ws.cell(row=2, column=1, value=label).font = Font(size=9, italic=True, color="55606A")
    return 4


def _no_data(ws, row: int, what: str) -> int:
    ws.cell(row=row, column=1,
            value=f"No source data — {what}. Fetch the export and re-run the pipeline "
                  "to populate this sheet.").font = NOTE_FONT
    return row + 2


def _visible_columns(df: pd.DataFrame, spec: list) -> list:
    """Drop spec columns absent or entirely empty for this slice of data."""
    out = []
    for header, field in spec:
        if field in df.columns and df[field].notna().any():
            out.append((header, field))
    return out


def _write_table(ws, row: int, df: pd.DataFrame, spec: list, block_title: str | None,
                 total_label: str = "Total") -> int:
    columns = _visible_columns(df, spec)
    if not columns:
        return row
    width = len(columns)

    if block_title:
        ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=width)
        cell = ws.cell(row=row, column=1, value=block_title)
        cell.font, cell.fill = BLOCK_FONT, BLOCK_FILL
        row += 1

    header_row = row
    for col, (header, _) in enumerate(columns, start=1):
        cell = ws.cell(row=row, column=col, value=header)
        cell.font, cell.fill, cell.border = HEAD_FONT, HEAD_FILL, BORDER
        cell.alignment = Alignment(horizontal="center", wrap_text=True)
    row += 1

    first_data = row
    for _, record in df.iterrows():
        for col, (_, field) in enumerate(columns, start=1):
            value = record.get(field)
            if pd.isna(value):
                value = None
            cell = ws.cell(row=row, column=col, value=value)
            cell.border = BORDER
            if field in FORMATS:
                cell.number_format = FORMATS[field]
        row += 1
    last_data = row - 1

    # Subtotal: sums for volumes, recomputed ratios (never an average of ratios).
    totals = {f: pd.to_numeric(df[f], errors="coerce").sum()
              for _, f in columns if f in SUMMABLE and f in df.columns}
    for col, (_, field) in enumerate(columns, start=1):
        cell = ws.cell(row=row, column=col)
        cell.font, cell.fill, cell.border = TOTAL_FONT, TOTAL_FILL, BORDER
        if col == 1:
            cell.value = total_label
        elif field in totals:
            cell.value = totals[field]
            cell.number_format = FORMATS.get(field, INT)
        elif field == "roas" and totals.get("spend"):
            cell.value = totals.get("revenue", 0) / totals["spend"]
            cell.number_format = NUM2
        elif field == "ctr" and totals.get("impressions"):
            cell.value = totals.get("clicks", 0) / totals["impressions"]
            cell.number_format = PCT
        elif field == "cpc" and totals.get("clicks"):
            cell.value = totals["spend"] / totals["clicks"]
            cell.number_format = MONEY2
        elif field == "conv_rate" and totals.get("clicks"):
            cell.value = totals.get("orders", 0) / totals["clicks"]
            cell.number_format = PCT
    row += 2

    _traffic_light(ws, columns, first_data, last_data)
    _fit(ws, {i: (42 if f in ("campaign_name", "product_name", "keyword") else 14)
              for i, (_, f) in enumerate(columns, start=1)})
    return row, header_row


def _traffic_light(ws, columns, first: int, last: int):
    """Green above healthy ROAS, amber above break-even, red below it."""
    if last < first:
        return
    for col, (_, field) in enumerate(columns, start=1):
        if field != "roas":
            continue
        letter = get_column_letter(col)
        span = f"{letter}{first}:{letter}{last}"
        ws.conditional_formatting.add(span, CellIsRule(
            operator="greaterThanOrEqual", formula=[str(config.HEALTHY_ROAS)],
            fill=PatternFill("solid", fgColor=GREEN), font=Font(color=GREEN_T)))
        ws.conditional_formatting.add(span, CellIsRule(
            operator="between", formula=[str(config.BREAKEVEN_ROAS), str(config.HEALTHY_ROAS)],
            fill=PatternFill("solid", fgColor=AMBER), font=Font(color=AMBER_T)))
        ws.conditional_formatting.add(span, CellIsRule(
            operator="lessThan", formula=[str(config.BREAKEVEN_ROAS)],
            fill=PatternFill("solid", fgColor=RED), font=Font(color=RED_T)))


def _category_sheet(wb, name: str, title: str, df: pd.DataFrame, entity: str,
                    period: tuple, missing_note: str):
    """One sheet, one block per coffee category, per the July workbook layout."""
    ws = wb.create_sheet(name[:31])
    row = _title(ws, title, period)
    if df.empty:
        _no_data(ws, row, missing_note)
        return ws

    spec = COLUMNS[entity]
    first_header = None
    for category in metrics.categories_for(df):
        block = df[df["category"] == category] if category else df[df["category"].isna()]
        if block.empty:
            continue
        block = metrics.collapse(block.copy(), entity)
        label = category or "Uncategorised"
        row, header_row = _write_table(ws, row, block, spec, label,
                                       total_label=f"{label} total")
        first_header = first_header or header_row
    if first_header:
        ws.freeze_panes = ws.cell(row=first_header + 1, column=1)
    return ws


