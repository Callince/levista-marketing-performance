def _executive_summary(wb, engine, period):
    ws = wb.create_sheet("Executive Summary")
    row = _title(ws, "Executive Summary", period, span=8)
    kpis = metrics.overall_kpis(engine)
    if not kpis:
        _no_data(ws, row, "no data was loaded")
        return

    cards = [
        ("Total Revenue", kpis["revenue"], MONEY),
        ("Total Ad Spend", kpis["spend"], MONEY),
        ("ROAS", kpis["roas"], NUM2),
        ("ROI", kpis["roi"], PCT),
        ("Orders", kpis["orders"], INT),
        ("Conversion Rate", kpis["conv_rate"], PCT),
    ]
    for i, (label, value, fmt) in enumerate(cards):
        col = 1 + i * 2
        ws.merge_cells(start_row=row, start_column=col, end_row=row, end_column=col + 1)
        head = ws.cell(row=row, column=col, value=label)
        head.font, head.fill = Font(size=9, bold=True, color="FFFFFF"), PatternFill("solid", fgColor="4A6572")
        head.alignment = Alignment(horizontal="center")
        ws.merge_cells(start_row=row + 1, start_column=col, end_row=row + 1, end_column=col + 1)
        cell = ws.cell(row=row + 1, column=col, value=None if value is None or pd.isna(value) else value)
        cell.font = Font(size=14, bold=True, color=BRAND)
        cell.alignment = Alignment(horizontal="center")
        cell.number_format = fmt
        cell.fill = PatternFill("solid", fgColor="F2F5F7")
    ws.row_dimensions[row + 1].height = 24
    row += 3

    table = metrics.platform_comparison(engine)
    row, header_row = _write_table(
        ws, row, table,
        [("Platform", "platform"), ("Revenue", "revenue"), ("Spend", "spend"),
         ("Orders", "orders"), ("ROAS", "roas"), ("CTR", "ctr"),
         ("Conv. Rate", "conv_rate"), ("Revenue Share", "revenue_share")],
        "Platform performance, best revenue first", total_label="All platforms")

    ws.cell(row=row, column=1, value="What happened, and what to do about it").font = \
        Font(size=12, bold=True, color=BRAND)
    row += 1
    narrative = ai.load(engine, __import__("db.models", fromlist=["insights"]).insights)
    for _, item in narrative.iterrows():
        ws.cell(row=row, column=1, value=item["platform"]).font = Font(bold=True, size=11)
        row += 1
        for heading, field in (("What happened", "what_happened"),
                               ("Why", "why_it_happened"),
                               ("What to do next", "what_to_do_next")):
            ws.cell(row=row, column=1, value=heading).font = Font(bold=True, size=9, color="55606A")
            ws.merge_cells(start_row=row, start_column=2, end_row=row, end_column=9)
            cell = ws.cell(row=row, column=2, value=item[field])
            cell.alignment = Alignment(wrap_text=True, vertical="top")
            ws.row_dimensions[row].height = 30
            row += 1
        row += 1

    ws.cell(row=row, column=1, value="What the numbers mean").font = Font(size=12, bold=True, color=BRAND)
    row += 1
    for term, meaning in GLOSSARY:
        ws.cell(row=row, column=1, value=term).font = Font(bold=True, size=9)
        ws.merge_cells(start_row=row, start_column=2, end_row=row, end_column=9)
        ws.cell(row=row, column=2, value=meaning).font = Font(size=9)
        row += 1
    _fit(ws, {1: 20, 2: 26, 3: 16, 4: 14, 5: 14, 6: 14, 7: 14, 8: 14, 9: 16})


def _comparison_sheet(wb, name: str, title: str, df: pd.DataFrame, spec: list,
                      period: tuple, missing_note: str, top: int = 60):
    ws = wb.create_sheet(name[:31])
    row = _title(ws, title, period, span=len(spec))
    if df.empty:
        _no_data(ws, row, missing_note)
        return
    df = df.sort_values("revenue", ascending=False, na_position="last").head(top)
    row, header_row = _write_table(ws, row, df, spec, None, total_label="Total (shown rows)")
    ws.freeze_panes = ws.cell(row=header_row + 1, column=1)
    ws.auto_filter.ref = f"A{header_row}:{get_column_letter(len(_visible_columns(df, spec)))}{header_row}"


def _recommendations_sheet(wb, engine, period):
    ws = wb.create_sheet("Recommendations")
    row = _title(ws, "Recommendations", period, span=6)
    df = ai.load(engine, recommendations)
    if df.empty:
        _no_data(ws, row, "no recommendations were generated")
        return
    df["_order"] = df["priority"].map(ai.PRIORITY_ORDER).fillna(9)
    df = df.sort_values(["_order", "impact_value"], ascending=[True, False])
    row, header_row = _write_table(
        ws, row, df,
        [("Priority", "priority"), ("Platform", "platform"), ("Type", "entity_type"),
         ("Name", "entity_name"), ("Action", "action"),
         ("Money at stake", "impact_value"), ("Why", "rationale")],
        None, total_label="")
    ws.freeze_panes = ws.cell(row=header_row + 1, column=1)
    ws.auto_filter.ref = f"A{header_row}:G{header_row}"
    _fit(ws, {1: 10, 2: 12, 3: 11, 4: 40, 5: 16, 6: 16, 7: 80})
    for r in range(header_row + 1, ws.max_row + 1):
        ws.cell(row=r, column=7).alignment = Alignment(wrap_text=True, vertical="top")
    ws.conditional_formatting.add(
        f"A{header_row + 1}:A{ws.max_row}",
        CellIsRule(operator="equal", formula=['"High"'],
                   fill=PatternFill("solid", fgColor=RED), font=Font(color=RED_T, bold=True)))
    ws.conditional_formatting.add(
        f"A{header_row + 1}:A{ws.max_row}",
        CellIsRule(operator="equal", formula=['"Medium"'],
                   fill=PatternFill("solid", fgColor=AMBER), font=Font(color=AMBER_T)))


def _alerts_sheet(wb, engine, period):
    ws = wb.create_sheet("Alerts & Anomalies")
    row = _title(ws, "Alerts & Anomalies", period, span=6)
    alert_df = ai.load(engine, alerts)
    if alert_df.empty:
        row = _no_data(ws, row, "no alerts were raised")
    else:
        alert_df["_order"] = alert_df["severity"].map(ai.PRIORITY_ORDER).fillna(9)
        alert_df = alert_df.sort_values("_order")
        row, header = _write_table(
            ws, row, alert_df,
            [("Severity", "severity"), ("Platform", "platform"), ("Type", "alert_type"),
             ("What", "entity_name"), ("Detail", "message")],
            "Alerts", total_label="")
        ws.conditional_formatting.add(
            f"A{header + 1}:A{row}",
            CellIsRule(operator="equal", formula=['"High"'],
                       fill=PatternFill("solid", fgColor=RED), font=Font(color=RED_T, bold=True)))

    anomaly_df = ai.load(engine, anomalies)
    if anomaly_df.empty:
        _no_data(ws, row, "no anomalies were detected")
    else:
        anomaly_df = anomaly_df.reindex(
            anomaly_df["z_score"].abs().sort_values(ascending=False).index)
        _write_table(ws, row, anomaly_df,
                     [("Platform", "platform"), ("Type", "entity_type"), ("Name", "entity_name"),
                      ("Measure", "metric"), ("Value", "value"), ("Typical", "cohort_mean"),
                      ("Std deviations", "z_score"), ("Direction", "direction")],
                     "Anomalies — unusually far from the norm for that platform",
                     total_label="")
    _fit(ws, {1: 12, 2: 14, 3: 16, 4: 34, 5: 90})


def _raw_summary_sheet(wb, engine, period):
    ws = wb.create_sheet("Raw Data Summary")
    row = _title(ws, "Raw Data Summary — every file the pipeline saw", period, span=8)
    with engine.connect() as conn:
        df = pd.read_sql(uploaded_files.select(), conn)
    if df.empty:
        _no_data(ws, row, "no files were processed")
        return
    df = df.sort_values(["processing_status", "platform", "filename"])
    row, header_row = _write_table(
        ws, row, df,
        [("File", "filename"), ("Platform", "platform"), ("Sub-platform", "sub_platform"),
         ("Report type", "report_type"), ("Sheet", "sheet_name"), ("Category", "category"),
         ("Rows", "row_count"), ("Status", "processing_status"), ("Note", "error")],
        None, total_label="Total rows")
    ws.freeze_panes = ws.cell(row=header_row + 1, column=1)
    ws.auto_filter.ref = f"A{header_row}:I{header_row}"
    _fit(ws, {1: 58, 2: 12, 3: 14, 4: 13, 5: 20, 6: 15, 7: 8, 8: 14, 9: 60})


