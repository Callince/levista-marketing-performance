# Every platform gets each report type it can produce, in the order Levista's spec
# lists them. Campaign first: it is the platform's full billed total, and four
# platforms previously had no campaign sheet at all, so an uploaded campaign report
# appeared only in the cross-platform sheet.
PLATFORM_SHEETS = {
    "Amazon":    ["campaign", "product", "keyword"],
    "Flipkart":  ["campaign", "product", "keyword"],
    # Only Instamart and Zepto report a city dimension.
    "Instamart": ["campaign", "product", "city", "keyword"],
    "Zepto":     ["campaign", "product", "city", "keyword"],
    "BigBasket": ["campaign", "product", "keyword"],
    "Blinkit":   ["campaign", "product", "keyword"],
}

SHEET_PLAN = [
    (f"{platform} {entity.capitalize()} Report", platform, entity,
     f"no {platform} {entity} report in the input folder")
    for platform, entities in PLATFORM_SHEETS.items()
    for entity in entities
]

FETCHERS = {"product": metrics.products, "keyword": metrics.keywords,
            "city": metrics.cities, "campaign": metrics.campaigns}


def build(engine=None, path=None, period_label=None):
    engine = engine or get_engine()
    period_label = period_label or metrics.latest_period(engine)
    prior = metrics.prior_period(engine, period_label)
    period = metrics.reporting_period(engine, period_label)
    # Say so in the header when the two months are different lengths, rather than
    # letting a per-day figure be read as a total.
    days = metrics.period_days(engine, period_label)
    prior_days = metrics.period_days(engine, prior) if prior else None
    uneven = bool(days and prior_days and abs(days - prior_days) / max(days, prior_days) > 0.05)
    growth_suffix = f" per day vs {prior}" if uneven else (f" vs {prior}" if prior else "")
    wb = Workbook()
    wb.remove(wb.active)

    _executive_summary(wb, engine, period)

    campaigns_all = metrics.campaigns(engine)
    _comparison_sheet(wb, "Overall Campaign Performance",
                      "Overall Campaign Performance — every platform",
                      campaigns_all,
                      [("Platform", "platform"), ("Sub-platform", "sub_platform")]
                      + COLUMNS["campaign"],
                      period, "no campaign data was loaded", top=200)

    for name, platform, entity, note in SHEET_PLAN:
        df = FETCHERS[entity](engine, platform=platform)
        _category_sheet(wb, name, f"{name}", df, entity, period, note)

    _comparison_sheet(wb, "Platform Comparison", "Platform Comparison",
                      metrics.platform_comparison(engine),
                      [("Platform", "platform"), ("Revenue", "revenue"), ("Spend", "spend"),
                       ("Orders", "orders"), ("Impressions", "impressions"),
                       ("Clicks", "clicks"), ("ROAS", "roas"), ("CTR", "ctr"),
                       ("CPC", "cpc"), ("Conv. Rate", "conv_rate"),
                       ("Revenue Share", "revenue_share"), ("Spend Share", "spend_share"),
                       ("Revenue Rank", "rank_revenue")]
                      + ([(f"Revenue Growth{growth_suffix}", "revenue_growth"),
                          (f"Spend Growth{growth_suffix}", "spend_growth"),
                          ("ROAS Change", "roas_change")] if prior else []),
                      period, "no platform data was loaded", top=50)

    _comparison_sheet(wb, "Product Comparison", "Product Comparison — across platforms",
                      metrics.collapse(metrics.products(engine), "product", ["platform"]),
                      [("Platform", "platform"), ("Category", "category")] + COLUMNS["product"],
                      period, "no product reports were found", top=120)
    _comparison_sheet(wb, "Keyword Comparison", "Keyword Comparison — across platforms",
                      metrics.collapse(metrics.keywords(engine), "keyword", ["platform"]),
                      [("Platform", "platform"), ("Category", "category")] + COLUMNS["keyword"],
                      period, "no keyword reports were found", top=150)
    _comparison_sheet(wb, "City Comparison", "City Comparison — across platforms",
                      metrics.collapse(metrics.cities(engine), "city", ["platform"]),
                      [("Platform", "platform"), ("Category", "category")] + COLUMNS["city"],
                      period, "no city reports were found", top=150)

    _recommendations_sheet(wb, engine, period)
    _alerts_sheet(wb, engine, period)
    _raw_summary_sheet(wb, engine, period)

    path = path or (config.OUTPUT_DIR / "Levista_Performance_Report.xlsx")
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    return path, len(wb.sheetnames)


